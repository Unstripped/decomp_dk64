import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
if str(REPO_ROOT / "tools") not in sys.path:
    sys.path.insert(0, str(REPO_ROOT / "tools"))

import protos  # noqa: E402

FIXTURE = """#include "common.h"
typedef struct Foo { s32 x; } Foo;
typedef struct { s32 y; } Bar;
typedef enum { E0, E1 } En;
typedef s32 Local;
void f(a) s32 a; {}
s32 g(Foo *p, u8 b) { return 0; }
void h(Bar *p) {}
static void st(void) {}
En e(Local l, f32 (*m)[4]) { return E0; }
s32 v(s32 n, ...) { return n; }
"""


def _fixture(tmp_path, text=FIXTURE):
    p = tmp_path / "a.c"
    p.write_text(text)
    return p


def test_header_declarations(tmp_path):
    text, skips = protos.header_text(str(_fixture(tmp_path)), "global", "a")
    lines = text.splitlines()
    assert lines[0].startswith("/* Generated by tools/protos.py gen from ")
    assert lines[1:4] == ["#ifndef PROTO_GLOBAL_A_H", "#define PROTO_GLOBAL_A_H", '#include "common.h"']
    assert "void f();" in lines
    assert "struct Foo;" in lines
    assert "s32 g(struct Foo *, u8);" in lines
    assert lines.index("struct Foo;") < lines.index("#ifndef PROTO_SKIP_f")
    assert "int e(s32, f32 (*)[4]);" in lines
    assert "s32 v(s32, ...);" in lines
    assert not any("st(" in s for s in lines)
    assert skips == [("h", "untagged local struct")]
    i = lines.index("void f();")
    assert lines[i - 1] == "#ifndef PROTO_SKIP_f" and lines[i + 1] == "#endif"
    assert lines[-1] == "#endif"


def test_by_value_local_struct_skipped(tmp_path):
    p = _fixture(tmp_path, '#include "common.h"\ntypedef struct S { s32 x; } S;\nvoid w(S s) {}\n')
    assert protos.header_text(str(p), "menu", "a")[1] == [("w", "by-value local struct")]


def test_tag_structs_then_header(tmp_path, capsys):
    p = _fixture(tmp_path, FIXTURE + "struct Baz { s32 z; };\ntypedef struct { s32 q; } Baz;\nvoid k(Baz *b) {}\n")
    protos.cmd_tag_structs(argparse.Namespace(src=str(p)))
    out = capsys.readouterr().out
    assert "TAG Bar" in out and "SKIP Baz: tag in use" in out
    assert "typedef struct Bar { s32 y; } Bar;" in p.read_text()
    text, skips = protos.header_text(str(p), "global", "a")
    assert "void h(struct Bar *);" in text.splitlines()
    assert skips == [("k", "untagged local struct")]


def test_scope_order():
    assert protos.scope("menu") == ["menu", "global", "boot"]
    assert protos.scope("global") == ["global", "boot"]
    assert protos.scope("boot") == ["boot"]
    table = {"menu": [("proto/menu/x.h", {"a": "void a(void)"})],
             "global": [("proto/global/y.h", {"a": "s32 a(void)", "b": "void b()"})]}
    assert protos.find_header("a", "menu", table)[0] == "proto/menu/x.h"
    assert protos.find_header("a", "race", table)[0] == "proto/global/y.h"
    assert protos.find_header("b", "boot", table) is None


def test_guard_and_text_helpers():
    assert protos.guard("global", "7130") == "PROTO_GLOBAL_7130_H"
    lines = ["/* c", "  more */", '#include "common.h"', "", '#include "actor.h"', "s32 x;", '#include "late.h"']
    assert protos.top_include(lines) == 4
    src = ["#ifndef NON_MATCHING", "void a(u8);", "#endif", "void b(void);",
           "#ifdef NON_MATCHING", "#if 0", "x", "#endif", "y", "#else", "z", "#endif"]
    assert protos.parked_regions(src) == {1, 2, 5, 6, 7, 8, 9, 10, 11}
