void actorCollisionProcessHit(Actor *targetActor, ActorCallbackNode *node) {
    s32 done;
    Actor *attacker;
    CollisionInteractionEntry *interactions;
    CollisionTableEntry *table;
    u8 entryAllowed;
    s32 i;
    PlayerState *playerState;
    u8 hitPhase;
    u8 curPhase;

    attacker = node->source;
    i = 0;
    done = 0;
    if (actorTableContains(attacker) && attacker->instanceId == ((CollisionHitRecord *)node->payload)->sourceId) {
        table = gActorTypeCollisionTables[targetActor->actorType].table;
        if (table == NULL) {
            if (attacker->flags & 0x20000) {
                actorCollisionRecordDefaultHit(attacker);
            }
        } else {
            interactions = actorCollisionFindTableEntry(table, attacker->actorType, attacker->collisionFlags);
            if ((attacker->flags & 0x80000) || (targetActor->flags & 0x80000)) {
                if (targetActor == attacker->parentActor || attacker == targetActor->parentActor) {
                    return;
                }
            }
            if (interactions == NULL) {
                if (attacker->flags & 0x20000) {
                    actorCollisionRecordDefaultHit(attacker);
                }
            } else {
                while (!done) {
                    if ((interactions[i].targetMask & targetActor->interactionType) && (interactions[i].attackerMask & attacker->interactionType)) {
                        if (interactions[i].filter != NULL) {
                            entryAllowed = interactions[i].filter(targetActor, attacker, node);
                        } else {
                            entryAllowed = 1;
                        }
                        if (entryAllowed) {
                            hitPhase = interactions[i].phase;
                            curPhase = gActorGlobalState.bossFightPhase;
                            if (curPhase < hitPhase) {
                                gActorGlobalState.targetActor = attacker;
                                gActorGlobalState.bossFightPhase = interactions[i].phase;
                            }
                            if (gActorGlobalState.collisionEventCount < 0xF) {
                                gActorGlobalState.collisionEventActors[gActorGlobalState.collisionEventCount] = attacker;
                                gActorGlobalState.collisionEvents[gActorGlobalState.collisionEventCount] = interactions[i].event;
                                gActorGlobalState.collisionEventCount++;
                                if (attacker->collisionFlags & 1) {
                                    playerState = attacker->customState;
                                    if (playerState->surfaceTimer != 0) {
                                        if (gActorTypeCollisionTables[targetActor->actorType].invulnBlocksDamage != 0) {
                                            switch (gActorGlobalState.collisionEvents[gActorGlobalState.collisionEventCount - 1]) {
                                            case 5:
                                            case 0xF:
                                                gActorGlobalState.collisionEventCount--;
                                                break;
                                            }
                                        }
                                    }
                                    if ((targetActor->collisionFlags & 2) && actorTypeStopsPlayerOnContact(targetActor->actorType)) {
                                        attacker->renderFlags |= 0x1000;
                                    }
                                }
                            }
                            if (interactions[i].chain == 0 || interactions[i].chain == 2) {
                                done = 1;
                            }
                        }
                    }
                    if (interactions[i].chain == 0) {
                        done = 1;
                    }
                    i++;
                }
                if (targetActor->flags & 0x20000000) {
                    gActorGlobalState.bossFightPhase = 1;
                }
                if (gActorGlobalState.bossFightPhase == 6 || gActorGlobalState.bossFightPhase == 7) {
                    actorApplyDamage(targetActor, attacker);
                }
                actorCollisionRunInteractionTable(targetActor, attacker);
            }
        }
    }
}

void actorCollisionRunInteractionTable(Actor *actorA, Actor *actorB) {
    s32 done;
    s32 found;
    s32 i;
    s32 j;

    done = 0;
    for (i = 0; !done; i++) {
        if (actorCollisionPatternMatches(actorA->actorType, actorA->collisionFlags, gActorInteractionTable[i].patternA) &&
            actorCollisionPatternMatches(actorB->actorType, actorB->collisionFlags, gActorInteractionTable[i].patternB) &&
            ((gActorInteractionTable[i].phase == -1) || gActorInteractionTable[i].phase == gActorGlobalState.bossFightPhase)) {
            if (gActorInteractionTable[i].event != -1) {
                found = 0;
                for (j = 0; !found && j < gActorGlobalState.collisionEventCount;) {
                    if (actorB == gActorGlobalState.collisionEventActors[j] && gActorGlobalState.collisionEvents[j] == gActorInteractionTable[i].event) {
                        found = 1;
                    } else {
                        j++;
                    }
                }
            } else {
                found = 1;
            }
            if (found) {
                gActorInteractionTable[i].handler(actorA, actorB, gActorInteractionTable[i].phase, gActorInteractionTable[i].event);
                switch (gActorInteractionTable[i].chain) {
                case 0:
                case 2:
                    done = 1;
                    break;
                }
            }
        }
        if (gActorInteractionTable[i].chain == 0) {
            done = 1;
        }
    }
}

s32 actorCollisionPatternMatches(s16 actorType, s16 actorFlags, s16 pattern) {
    if (pattern == actorType) {
        return 1;
    }
    switch (pattern) {
    case -1:
        if (actorFlags == 1) {
            return 1;
        }
        break;
    case -2:
        if (actorFlags == 2) {
            return 1;
        }
        break;
    case -8:
        if (actorFlags == 0x80) {
            return 1;
        }
        break;
    case -3:
        if (actorFlags == 4) {
            return 1;
        }
        break;
    case -4:
        if (actorFlags == 8) {
            return 1;
        }
        break;
    case -5:
        if (actorFlags == 0x10) {
            return 1;
        }
        break;
    case -6:
        if (actorFlags == 0x20) {
            return 1;
        }
        break;
    case -7:
        if (actorFlags == 0x40) {
            return 1;
        }
        break;
    }
    return 0;
}


void actorCollisionRecordDefaultHit(Actor *actor) {
    if (gActorGlobalState.bossFightPhase < 2) {
        gActorGlobalState.targetActor = actor;
        gActorGlobalState.bossFightPhase = 1;
    }
    if (gActorGlobalState.collisionEventCount < 0xF) {
        gActorGlobalState.collisionEventActors[gActorGlobalState.collisionEventCount] = actor;
        gActorGlobalState.collisionEvents[gActorGlobalState.collisionEventCount] = 2;
        gActorGlobalState.collisionEventCount++;
    }
}

void actorApplyDamage(Actor *target, Actor *attacker) {
    if ((target->health -= attacker->damage) <= 0) {
        gActorGlobalState.bossFightPhase = 9;
        return;
    }
    if (gActorGlobalState.bossFightPhase == 6) {
        gActorGlobalState.bossFightPhase = 4;
    }
    if (gActorGlobalState.bossFightPhase == 7) {
        gActorGlobalState.bossFightPhase = 5;
    }
}

CollisionInteractionEntry *actorCollisionFindTableEntry(CollisionTableEntry *table, s16 actorType, s16 actorFlags) {
    s32 pattern;
    CollisionInteractionEntry *entries;
    s32 match;

    do {
        pattern = table->pattern;
        entries = table->entries;
        match = actorCollisionPatternMatches(actorType, actorFlags, pattern);
        table++;
    } while (!match && pattern != 0);
    return entries;
}

void actorCollisionCheckBoundingBoxes(Actor *actor) {
    s16 animId;
    s16 frame;
    s32 index;
    s32 retry;
    s32 done;
    CollisionThresholdEntry *entry;
    PlayerState *playerState;
    u8 pad;
    u8 valid;

    done = 0;
    index = 0;
    animId = actor->sub4->model->animId;
    playerState = actor->customState;
    frame = actor->sub4->model->frame;
    retry = 0;
    valid = 1;

    if (animId == -1) {
        actor->interactionType = 0;
        return;
    }

    if (playerState->animThresholdIndex != -1) {
        index = playerState->animThresholdIndex;
        retry = 1;
    }

    do {
        if (sCollisionAnimThresholds[index].animId == -1) {
            done = 1;
        } else if (animId == sCollisionAnimThresholds[index].animId) {
            if ((frame >= sCollisionAnimThresholds[index].frameMin) && (frame <= sCollisionAnimThresholds[index].frameMax)) {
                entry = &sCollisionAnimThresholds[index];
                actor->interactionType = entry->interactionType;
                actor->damage = entry->damage;
                if (entry->flags & 1) {
                    actor->renderFlags |= 0x80;
                } else {
                    actor->renderFlags &= ~0x80;
                }
                actorCollisionUpdateNodeFlags(actor, entry->nodeFlagSet);
                if (valid) {
                    playerState->animThresholdIndex = index;
                } else {
                    playerState->animThresholdIndex = -1;
                }
                return;
            }
            valid = 0;
        }

        if (retry) {
            index = 0;
            retry = 0;
            done = 0;
        } else {
            index++;
        }
    } while (!done);

    actor->interactionType = 0;
    actor->damage = 0;
}


void actorCollisionUpdateNodeFlags(Actor *actor, u8 flagIndex) {
    s32 match;
    s16 i;
    s8 *ptr;

    actorCollisionOverrideNodeFlagSet(actor, &flagIndex);
    actorClearAllNodeFlags(actor);
    ptr = sCollisionNodeFlagSets[flagIndex];
    if (*ptr != -1) {
        do {
            actorSetNodeFlag(actor, *ptr);
            match = 0;
            for (i = 0; i < 24 && !match;) {
                if ((actor->actorType == sCollisionNodeValues[i].actorType) && (*ptr == sCollisionNodeValues[i].node)) {
                    actorSetNodeValue(actor, *ptr, sCollisionNodeValues[i].value);
                    match = 1;
                } else {
                    actorSetNodeValue(actor, *ptr, 0);
                    i++;
                }
            }
            ptr++;
        } while (*ptr != -1);
    }
}

extern s32 gCurrentMap;
void actorCollisionOverrideNodeFlagSet(Actor *actor, u8 *outFlagIndex) {
    if ((gCurrentMap == 0x53) && (actor->actorType == 6) && (actor->state == 0x1E)) {
        *outFlagIndex = 0x15;
    }
}


